"""Consume actual publisher output through the shipping desktop and installer."""
from __future__ import annotations

import asyncio
import hashlib
import json
from pathlib import Path
import shutil
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[2]


async def exercise_publication(product, invocation):
    from playwright.async_api import expect
    from tools.probes.extension_store_demo import Publisher, sha256
    from tools.probes.extension_release_shell import evaluate_main
    from tools.probes.extension_startup import confirm_update
    from tools.smoke_electron_model_less import _wait_enabled
    from config.process_tree import ProcessTree

    publisher = await asyncio.to_thread(
        Publisher, product.run_root / "publisher", json.loads(invocation.read_text())
    )
    report = {
        "ok": False, "checks": [], "observed_catalogs": [], "app_restarts": 0,
        "authority": "local simulated review and protected-base refs; not public approval",
        "native_confirmation": "automated in owned inspector",
        "damage": "NUL bytes injected only while owned application is stopped; not physical power loss",
        "runtime_contracts": [],
    }
    state_path = product.run_root / "state/electron-user-data/settings.json"
    cache = state_path.parent / "extension-catalog/index.json"
    theme, notes = "com.example.desktop-theme", "com.example.notes-mcp"

    def save():
        (product.run_root / "extension-publication-report.json").write_text(
            json.dumps(report, indent=2), encoding="utf-8"
        )

    def check(name, valid=True):
        if not valid:
            raise AssertionError(name)
        report["checks"].append(name)
        save()

    def settings():
        return json.loads(state_path.read_text(encoding="utf-8"))

    async def main(expression):
        return await evaluate_main(product, expression)

    async def transport():
        assert await main(f'(async()=>{{{transport_script()};return true}})()')

    def transport_script():
        code = (ROOT / "electron/tests/fixtures/extensionPublication.cjs").read_text()
        return (code + f';await setupPublicationTransport({json.dumps(publisher.origin)},'
                f'{json.dumps(str(publisher.root / "cert.pem"))});')

    async def catalog(request):
        return await asyncio.wait_for(
            product.page.evaluate("r=>window.amadeus.extensionCatalog(r)", request), 180
        )

    async def refresh(action="refresh"):
        response = await catalog({"action": action})
        assert response["ok"], response.get("error")
        digest = sha256(cache)
        assert digest == sha256(publisher.current), "Desktop did not consume exact generated bytes"
        assert response["catalog"]["sequence"] == publisher.sequence
        report["observed_catalogs"].append({
            "sequence": publisher.sequence, "sha256": digest, "action": action
        })
        save()
        return response

    async def button(name):
        await (
            product.page.get_by_role("button", name=name, exact=True)
            .and_(product.page.locator("button:enabled")).click(timeout=30000)
        )

    async def open_manager():
        await button("Plugins")

    async def install_ui(package_id, version):
        await product.page.get_by_role("tab", name="Browse", exact=True).click()
        await product.page.get_by_role("searchbox").fill(package_id)
        await button("View plugin details")
        selection = product.page.locator(".extension-catalog-detail select")
        if await selection.count():
            await selection.select_option(version)
        await button("Schedule this version for next app start…")
        await apply_scheduled(package_id, version)
        await expect(product.page.locator("#extension-panel-installed")).to_be_visible(timeout=120000)
        await expect(product.page.locator(f'[data-extension-id="{package_id}"][data-extension-version="{version}"]')).to_be_visible(timeout=120000)
        await expect(product.page.locator(".extension-download-progress")).to_have_count(0, timeout=120000)
        record = settings()["extensions"][package_id]
        entry = next(e for e in json.loads(publisher.current.read_text())["entries"]
                     if e["id"] == package_id and e["version"] == version)
        assert record["digest"] == entry["sha256"]
        return record

    async def update_ui(package_id, version):
        await product.page.get_by_role("tab", name="Installed", exact=True).click()
        old = settings()["extensions"][package_id]["version"]
        text = product.page.locator(f'[data-extension-id="{package_id}"][data-extension-version="{old}"]')
        card = product.page.locator("#extension-panel-installed .setting-card").filter(has=text)
        await card.get_by_role("button", name="Schedule update for next app start…", exact=True).click()
        await apply_scheduled(package_id, version)
        await expect(product.page.locator(f'[data-extension-id="{package_id}"][data-extension-version="{version}"]')).to_be_visible(timeout=120000)
        await expect(product.page.locator(".extension-download-progress")).to_have_count(0, timeout=120000)
        entry = next(e for e in json.loads(publisher.current.read_text())["entries"]
                     if e["id"] == package_id and e["version"] == version)
        assert settings()["extensions"][package_id]["digest"] == entry["sha256"]
        if package_id == notes:
            await notes_contract('updated-before-keep')
        else:
            assert (await product.page.evaluate('window.amadeus.getDesktopTheme()'))['theme']['version'] == version
        await confirm_update(product, package_id, version)

    async def apply_scheduled(package_id, version):
        await expect(product.page.get_by_text('Scheduled for the next app start. Installed packages have not changed. Review the native confirmation before installation.', exact=True)).to_be_visible(timeout=30000)
        previous = settings()['extensions'].get(package_id)
        assert previous is None or previous['version'] != version
        await restart()
        await open_manager()
        await product.page.get_by_role('tab', name='Installed', exact=True).click()
        assert not (await catalog({'action':'get'}))['catalog'].get('scheduledInstall')

    async def configure(package_id):
        await product.page.get_by_role("tab", name="Installed", exact=True).click()
        card = product.page.locator("#extension-panel-installed .setting-card").filter(
            has=product.page.locator(f'[data-extension-id="{package_id}"]'))
        if package_id == notes:
            await card.get_by_role("button", name="Configure extension", exact=True).click()
            await (card.locator(".settings-form-provider-choices label")
                   .filter(has_text="Pi").locator("input").check())
            await button("Save extension")
            await expect(card.locator('form[aria-label="Configure extension"]')).to_have_count(0, timeout=30000)
        toggle = card.locator('[role="switch"][id^="extension-enabled-"]')
        if await toggle.get_attribute("aria-checked") != "true":
            await toggle.click()
        await expect(toggle).to_have_attribute("aria-checked", "true", timeout=30000)

    async def select_theme():
        response = await product.page.evaluate(
            "window.amadeus.updateDesktopSettings({values:{AMADEUS_UI_THEME:'com.example.desktop-theme/day'}})"
        )
        assert response["ok"], response.get("error")
        assert (await product.page.evaluate("window.amadeus.getDesktopTheme()")).get("theme")

    async def restart(*, damage=(), offline=False):
        previous_pid = product.process.pid
        await main("(()=>{setImmediate(()=>process.getBuiltinModule('module').createRequire(process.execPath)('electron').app.quit());return true})()")
        await asyncio.to_thread(product.process.wait, 30)
        await product.stop()
        assert product.process.poll() is not None
        report["app_restarts"] += 1
        shutil.copyfile(product.log_path, product.run_root / f"restart-{report['app_restarts']}-previous.log")
        for path in damage:
            assert path.resolve().is_relative_to(product.run_root.resolve())
            assert not path.is_symlink()
            path.write_bytes(b"\0" * 1536)
        publisher.offline = offline
        await product.start(startup_timeout=180, main_startup_script=transport_script())
        await _wait_enabled(product.page.locator('textarea[placeholder*="Type a message"]'), timeout=60)
        assert product.process.pid != previous_pid

    async def notes_contract(label):
        record = settings()["extensions"][notes]
        directory = state_path.parent / "extensions" / record["installId"]
        saved = {k: record[k] for k in
                 ("id", "version", "revision", "digest", "manifest", "enabled", "providers")}
        saved.update(
            package_path=str(directory / "venv" / record["sitePackages"] / record["packageRoot"]),
            python_path=str(directory / "venv/Scripts/python.exe"),
            data_path=str(state_path.parent / "extension-data" / hashlib.sha256(notes.encode()).hexdigest()),
            config=record["values"], secrets={},
        )
        record_path = product.run_root / f"{label}-record.json"
        record_path.write_text(json.dumps(saved), encoding="utf-8")
        output = product.run_root / f"{label}-contract.json"
        wheel = publisher.wheels[f"amadeus_example_notes_mcp-{record['version']}-py3-none-any.whl"]

        def run():
            with (product.run_root / f"{label}-contract.log").open("w", encoding="utf-8") as log:
                proc = subprocess.Popen([
                    sys.executable, "-I", str(ROOT / "tools/check_extension_contract.py"), "--execute",
                    "--kind", "mcp", "--wheel", str(wheel), "--record", str(record_path),
                    "--scenario", str(ROOT / "examples/extensions/contract-scenarios/notes.json"),
                    "--output", str(output),
                ], cwd=ROOT, env=product._environment(), stdout=log, stderr=subprocess.STDOUT)
                tree = ProcessTree(proc)
                try:
                    return proc.wait(timeout=90)
                finally:
                    tree.terminate()

        assert await asyncio.to_thread(run) == 0, f"Notes runtime contract failed: {label}"
        evidence = json.loads(output.read_text())
        assert evidence["ok"], evidence
        report["runtime_contracts"].append({
            "label": label, "id": notes, "version": record["version"],
            "sha256": record["digest"], "ok": True,
            "scope": "installed wheel through native MCP client save/read/list; no model turn",
        })
        save()

    async def rejects_install(package_id):
        response = await catalog({"action": "schedule", "id": package_id, "version": "0.2.0"})
        assert not response["ok"], "Rejected artifact unexpectedly installed"
        return response

    try:
        await asyncio.to_thread(publisher.publish, "initial", version="0.1.0")
        await transport()
        await open_manager()
        await refresh()
        check("initial CLI-generated catalog reaches desktop byte-for-byte")
        await install_ui(theme, "0.1.0")
        await configure(theme)
        await select_theme()
        await install_ui(notes, "0.1.0")
        await configure(notes)
        await notes_contract("initial")
        check("real resource and MCP packages install and run from first publication")
        await product.screenshot("publication-initial")

        await asyncio.to_thread(publisher.publish, "update", version="0.2.0")
        assert (await product.page.evaluate(
            "v=>window.amadeus.updateDesktopSettings({values:{AMADEUS_EXTENSION_ARTIFACT_MIRROR:v}})",
            publisher.origin + "/mirror",
        ))["ok"]
        await refresh()
        await button("Check updates and security status")
        # Exercise the actual Installed-view manual update controls.
        await update_ui(theme, "0.2.0")
        await update_ui(notes, "0.2.0")
        check("both manual updates preserve enablement and Notes binding",
              all(settings()["extensions"][p]["enabled"] for p in (theme, notes))
              and settings()["extensions"][notes]["providers"] == ["pi"])
        check("updated wheel bytes downloaded through actual mirror HTTPS",
              all(any(r["path"] == "/mirror/" + sha256(publisher.wheels[f"amadeus_example_{name}-0.2.0-py3-none-any.whl"])
                      + "/" + f"amadeus_example_{name}-0.2.0-py3-none-any.whl"
                      and r["status"] == 200 and r["client"] == "desktop"
                      for r in publisher.requests) for name in ("theme", "notes_mcp")))
        await restart()
        check("new app process retains updated installs and enabled theme",
              all(settings()["extensions"][p]["version"] == "0.2.0" for p in (theme, notes))
              and bool((await product.page.evaluate("window.amadeus.getDesktopTheme()")).get("theme")))
        await notes_contract("updated-restart")
        await refresh()

        await asyncio.to_thread(publisher.publish, "copyright-withdrawal", withdrawal=True)
        await refresh()
        rejection = await rejects_install(notes)
        check("copyright withdrawal stops redistribution without security ban",
              "withdrawn" in rejection["error"] and not settings()["extensionSecurity"]["decisions"])
        await notes_contract("withdrawn-installed")
        check("existing withdrawn MCP installation remains usable")

        blocked = await asyncio.to_thread(publisher.publish, "security-block", decision="blocked")
        await refresh()
        check("security publication blocks both exact installed artifacts",
              {e["id"]: e["blocked"] for e in (await catalog({"action": "get"}))["catalog"]["installed"]} == {theme: True, notes: True})
        check("security block removes applied theme",
              not (await product.page.evaluate("window.amadeus.getDesktopTheme()")).get("theme"))
        await rejects_install(theme)
        denied = await product.page.evaluate("id=>window.amadeus.updateExtension({id,enabled:true})", notes)
        check("blocked MCP cannot be activated", not denied["ok"] and "blocked" in denied["error"])
        await open_manager()
        await product.screenshot("publication-blocked")

        cache.unlink()
        await restart(damage=[state_path], offline=True)
        check("offline new process restores known bans from backup with no display cache",
              settings()["extensionSecurity"]["sequence"] == 4
              and {e["id"]: e["blocked"] for e in (await catalog({"action": "get"}))["catalog"]["installed"]} == {theme: True, notes: True}
              and not cache.exists())
        wheel = publisher.wheels["amadeus_example_theme-0.2.0-py3-none-any.whl"]
        await main(
            "(()=>{const e=process.getBuiltinModule('module').createRequire(process.execPath)('electron');"
            "e.dialog.showOpenDialog=async()=>({canceled:false,filePaths:[" + json.dumps(str(wheel)) + "]});return true})()"
        )
        local = await product.page.evaluate("window.amadeus.installExtension()")
        assert local['ok'] and local['scheduled']
        previous = settings()['extensions'][theme]['installId']
        await restart(offline=True)
        local_state = await product.page.evaluate('window.amadeus.getDesktopSettings()')
        check("known ban rejects scheduled local bytes at offline startup",
              settings()['extensions'][theme]['installId'] == previous
              and any('blocked' in error for error in local_state['extensionErrors'])
              and not (await catalog({'action':'get'}))['catalog'].get('scheduledInstall'))

        await restart(damage=[state_path, state_path.with_suffix(".json.bak")], offline=True)
        check("double NUL damage persists safety unavailable after restart",
              settings()["extensionSecurity"]["status"] == "unavailable")
        assert (await product.page.evaluate(
            "window.amadeus.updateDesktopSettings({values:{AMADEUS_UI_LOCALE:'en-US'}})"
        ))["ok"]
        publisher.offline = False
        check("ordinary save and refresh cannot clear corruption",
              not (await catalog({"action": "refresh"}))["ok"]
              and settings()["extensionSecurity"]["status"] == "unavailable")
        await refresh("recover")
        check("explicit recovery restores published bans without fabricating lost inventory",
              not settings()["extensions"]
              and all(d["blocked"] for d in settings()["extensionSecurity"]["decisions"])
              and len(settings()["extensionSecurity"]["decisions"]) == 2)
        await rejects_install(theme)

        await asyncio.to_thread(publisher.publish, "security-unblock", decision="allowed")
        await refresh()
        check("higher publication explicitly unblocks both artifacts",
              settings()["extensionSecurity"]["sequence"] == 5
              and all(not d["blocked"] and d["sequence"] == 5 for d in settings()["extensionSecurity"]["decisions"]))
        rejection = await rejects_install(notes)
        check("security unblocking does not remove independent copyright withdrawal",
              "withdrawn" in rejection["error"])
        await open_manager()
        await install_ui(theme, "0.2.0")
        await configure(theme)
        await select_theme()

        await asyncio.to_thread(publisher.publish, "restore-distribution", withdrawal=False)
        await refresh()
        await install_ui(notes, "0.2.0")
        await configure(notes)
        await notes_contract("restored")
        check("separate restoration allows real MCP install and execution again")

        # Replay a real previously valid publication, not a mutated test index.
        newest = publisher.current
        publisher.current = publisher.root / "04-security-block/index.json"
        check("old authentic blocked snapshot cannot roll back explicit unban",
              not (await catalog({"action": "refresh"}))["ok"]
              and settings()["extensionSecurity"]["sequence"] == 6
              and all(not d["blocked"] for d in settings()["extensionSecurity"]["decisions"]))
        publisher.current = newest
        await refresh()
        cache.unlink()
        await restart(damage=[state_path], offline=True)
        check("unban and maximum publication sequence survive damage and offline restart",
              settings()["extensionSecurity"]["sequence"] == 6
              and all(not d["blocked"] for d in settings()["extensionSecurity"]["decisions"])
              and {e["id"]: e["blocked"] for e in (await catalog({"action": "get"}))["catalog"]["installed"]} == {theme: False, notes: False}
              and not cache.exists())
        check("restored theme still applies after offline backup recovery",
              bool((await product.page.evaluate("window.amadeus.getDesktopTheme()")).get("theme")))
        await notes_contract("restored-offline")
        publisher.offline = False
        await refresh()
        await open_manager()
        await product.screenshot("publication-restored")
        check("all six snapshots passed input CI, publication CI and exact rebuild",
              len(publisher.phases) == 6 and all(p["input_ci"] and p["publication_ci"] and p["exact_rebuild"] for p in publisher.phases))
        check("maintenance checker fetched exact wheels over HTTPS",
              all(any(r["path"] == "/artifacts/" + p.name and r["status"] == 200
                      and r["client"] == "maintainer" and r["sha256"] == sha256(p)
                      for r in publisher.requests) for p in publisher.wheels.values()))
        check("completed operations leave no download staging",
              not list((cache.parent / "staging").iterdir()))
        await asyncio.to_thread(publisher.verify_rejections)
        check("publication tools reject tampered generated output and missing safety facts")
        check("submission revision precedes approval without a second author submission",
              publisher.phases[0]["submission_revision"]["same_submission"]
              and publisher.phases[0]["submission_revision"]["approval_was_not_granted"])
        check("all six publications verify candidate and live distribution with fresh assets",
              all(p["candidate_delivery"] and p["live_delivery"] for p in publisher.phases))
        report["blocked_identities"] = blocked["security"]
        report["ok"] = True
        return report
    except Exception as error:
        report['error'] = f'{type(error).__name__}: {error}'
        try:
            await product.screenshot("publication-failure")
        except Exception as capture_error:
            report['capture_error'] = str(capture_error)
        raise
    finally:
        await asyncio.to_thread(publisher.close)
        report["publications"] = publisher.phases
        save()
